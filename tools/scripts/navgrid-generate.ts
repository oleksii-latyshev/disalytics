import { mapFloors } from '../../packages/map-data/src/floors';
import { FLOOR_DATA } from '../../packages/map-data/src/generated/floors';
import {
  MAP_IDS,
  MAP_OVERVIEWS,
  type MapId,
  RADAR_IMAGE_SIZE,
} from '../../packages/map-data/src/generated/overviews';
import { plateLevelIndex } from '../../packages/map-data/src/layout';
import { NAV_OVERRIDES } from '../../packages/map-data/src/navgrid-overrides';
import { snapToWalkable } from '../../packages/map-data/src/pathfinding';
import { mapSpawns } from '../../packages/map-data/src/spawns';
import { radarX, radarY } from '../../packages/map-data/src/transform';
import type { NavConnector } from '../../packages/map-data/src/types';
import { dilate, subtract, unpackBits } from './floors/connectors';
import { applyRects, keepComponents, packBits, traceLevel } from './navgrid/trace';

/**
 * Traces a walkable grid per map level from the vanilla radar images.
 *
 *     bun run navgrid:generate
 *     DISALYTICS_NAVGRID_DEBUG=<dir> bun run navgrid:generate     # also writes a mask-over-radar PNG per level
 *
 * 4 px cells (256 x 256 over the 1024 px image) with walls grown by 2 px: at 8 px cells a narrow
 * doorway lost its cells to the 50% share rule and split Anubis, Overpass and Nuke's lower floor;
 * 4 px keeps them joined. Hand corrections are `navgrid-overrides.ts`.
 *
 * One grid per floor (`mapFloors`): the overview's levels, then each authored extra floor. An extra
 * floor shares its image with the floor above it, so its grid is the cells its players' tracks
 * covered (`floors:generate`) that the image draws as ground, and the cells only it covered are cut
 * out of the shared floor, so a route on that floor cannot shortcut through its corridor. The
 * connectors `floors:generate` found are snapped onto walkable cells and written beside the grids.
 */
const PACKAGE_DIR = 'packages/map-data';
const VANILLA_DIR = `${PACKAGE_DIR}/assets/radar/vanilla`;
const OUTPUT_DIR = `${PACKAGE_DIR}/src/generated/navgrids`;
const DEBUG_ENV = 'DISALYTICS_NAVGRID_DEBUG';
const CELL = 4;
const ERODE = 2;
/** A component this share of the largest, or smaller but holding a spawn, is kept. */
const MIN_SHARE = 0.02;
const SPAWN_REACH = 8;
/** Cells the shared floor's own tracks are grown by before they protect it from a cut. */
const SHARED_MARGIN = 2;

/** The nearest walkable cell to `(sx, sy)` within `SPAWN_REACH`, or -1. */
function nearestWalkable(grid: Uint8Array, cells: number, sx: number, sy: number): number {
  for (let r = 0; r <= SPAWN_REACH; r++) {
    for (let dy = -r; dy <= r; dy++) {
      for (let dx = -r; dx <= r; dx++) {
        const x = sx + dx;
        const y = sy + dy;
        const inside = x >= 0 && y >= 0 && x < cells && y < cells;
        if (inside && grid[y * cells + x] === 1) return y * cells + x;
      }
    }
  }
  return -1;
}

function seedsFor(id: MapId, levelIndex: number, grid: Uint8Array, cells: number): number[] {
  const overview = MAP_OVERVIEWS[id];
  const spawns = [...mapSpawns(id, 'T'), ...mapSpawns(id, 'CT')];

  return spawns
    .filter((spawn) => plateLevelIndex(overview, spawn.z) === levelIndex)
    .map((spawn) =>
      nearestWalkable(
        grid,
        cells,
        Math.floor(radarX(overview, spawn.x) / CELL),
        Math.floor(radarY(overview, spawn.y) / CELL),
      ),
    )
    .filter((seed) => seed >= 0);
}

type Rgb = [number, number, number];

function tinted(r: number, g: number, b: number, a: number, walk: boolean): Rgb {
  if (walk) return [r * 0.5, g * 0.5 + 128, b * 0.5];
  return a >= 200 ? [r * 0.4 + 150, g * 0.4, b * 0.4] : [255, 255, 255];
}

/** The level's mask laid over its radar: walkable green, traced-out floor red, void white. */
function debugImage(png: PNG, grid: Uint8Array, size: number): Buffer {
  const out = new PNG({ width: png.width, height: png.height });
  for (let y = 0; y < png.height; y++) {
    for (let x = 0; x < png.width; x++) {
      const i = (y * png.width + x) * 4;
      const walk = grid[Math.floor(y / CELL) * size + Math.floor(x / CELL)] === 1;
      const [r, g, b] = tinted(
        png.data[i] ?? 0,
        png.data[i + 1] ?? 0,
        png.data[i + 2] ?? 0,
        png.data[i + 3] ?? 0,
        walk,
      );
      out.data[i] = Math.round(r);
      out.data[i + 1] = Math.round(g);
      out.data[i + 2] = Math.round(b);
      out.data[i + 3] = 255;
    }
  }
  return PNG.sync.write(out);
}

function renderConnector(connector: NavConnector): string {
  const point = (p: NavConnector['a']) => `{ floor: ${p.floor}, x: ${p.x}, y: ${p.y} }`;
  const oneWay = connector.isOneWay === true ? ', isOneWay: true' : '';
  return `    { a: ${point(connector.a)}, b: ${point(connector.b)}${oneWay} },`;
}

function render(levels: string[], size: number, connectors: readonly NavConnector[]): string {
  const joins =
    connectors.length === 0 ? [] : ['  connectors: [', ...connectors.map(renderConnector), '  ],'];
  return [
    '// Generated by `bun run navgrid:generate` from the vanilla radar images and navgrid-overrides.ts.',
    '// Traced from a picture, not a nav mesh. Edit the overrides, not this file.',
    '',
    "import type { NavGridData } from '../../types';",
    '',
    'export const NAV_GRID: NavGridData = {',
    `  cell: ${CELL},`,
    `  size: ${size},`,
    '  levels: [',
    ...levels.map((level) => `    '${level}',`),
    '  ],',
    ...joins,
    '};',
    '',
  ].join('\n');
}

async function readLevelImage(image: string): Promise<PNG> {
  const file = Bun.file(`${VANILLA_DIR}/${image}.png`);
  const png = PNG.sync.read(Buffer.from(await file.arrayBuffer()));
  if (png.width !== RADAR_IMAGE_SIZE || png.height !== RADAR_IMAGE_SIZE) {
    throw new Error(`${image}.png is ${png.width}x${png.height}, expected ${RADAR_IMAGE_SIZE}`);
  }
  return png;
}

function unpackMask(base64: string, cells: number): Uint8Array {
  return unpackBits(new Uint8Array(Buffer.from(base64, 'base64')), cells);
}

interface TracedMap {
  readonly levels: string[];
  readonly connectors: NavConnector[];
}

/** The grids of the overview's levels as traced, with each extra floor cut out of the one it shares. */
function applyExtraFloors(id: MapId, traced: Uint8Array[], size: number): Uint8Array[] {
  const extras = mapFloors(MAP_OVERVIEWS[id]).filter((floor) => floor.isExtra);
  const grids: Uint8Array[] = [];
  const cuts: { level: number; cut: Uint8Array }[] = [];

  for (const extra of extras) {
    const masks = FLOOR_DATA[id]?.masks?.[extra.id];
    const base = traced[extra.level];
    if (masks === undefined || base === undefined) {
      throw new Error(`${id} has an ${extra.id} floor but no tracks for it: run floors:generate.`);
    }
    const own = unpackMask(masks.own, size * size);
    const shared = dilate(unpackMask(masks.shared, size * size), size, SHARED_MARGIN);
    grids.push(own);
    cuts.push({ level: extra.level, cut: subtract(own, shared) });
  }

  for (const { level, cut } of cuts) {
    const base = traced[level];
    if (base !== undefined) traced[level] = subtract(base, cut);
  }
  return grids;
}

function snapConnectors(id: MapId, grids: readonly Uint8Array[], size: number): NavConnector[] {
  const levels = grids.map((walkable) => ({ cell: CELL, size, walkable }));
  const snapped: NavConnector[] = [];

  for (const connector of FLOOR_DATA[id]?.connectors ?? []) {
    const a = levels[connector.a.floor];
    const b = levels[connector.b.floor];
    const from = a === undefined ? undefined : snapToWalkable(a, connector.a);
    const to = b === undefined ? undefined : snapToWalkable(b, connector.b);
    if (from === undefined || to === undefined) {
      console.warn(
        `${id}: a connector at ${connector.a.x},${connector.a.y} has no ground, dropped.`,
      );
      continue;
    }
    snapped.push({
      a: { floor: connector.a.floor, x: Math.round(from.x), y: Math.round(from.y) },
      b: { floor: connector.b.floor, x: Math.round(to.x), y: Math.round(to.y) },
      ...(connector.isOneWay === true ? { isOneWay: true } : {}),
    });
  }
  return snapped;
}

async function traceOverviewLevels(
  id: MapId,
  size: number,
): Promise<{ pngs: PNG[]; traced: Uint8Array[] }> {
  const pngs: PNG[] = [];
  const traced: Uint8Array[] = [];

  for (const [levelIndex, level] of MAP_OVERVIEWS[id].levels.entries()) {
    const png = await readLevelImage(level.image);
    pngs.push(png);

    const grid = traceLevel(png.data, RADAR_IMAGE_SIZE, { cell: CELL, erode: ERODE });
    for (const override of NAV_OVERRIDES[id] ?? []) {
      if (override.level !== levelIndex) continue;
      applyRects(grid, size, CELL, override.open, 1);
      applyRects(grid, size, CELL, override.close, 0);
    }
    traced.push(grid);
  }
  return { pngs, traced };
}

async function writeDebug(
  id: MapId,
  pngs: readonly PNG[],
  grids: readonly Uint8Array[],
  size: number,
  debugDir: string,
): Promise<void> {
  const overview = MAP_OVERVIEWS[id];
  for (const [floor, info] of mapFloors(overview).entries()) {
    const png = pngs[info.level];
    const grid = grids[floor];
    const image = overview.levels[info.level]?.image;
    if (png === undefined || grid === undefined || image === undefined) continue;
    const name = info.isExtra ? `${image}-${info.id}` : image;
    await Bun.write(`${debugDir}/${name}.png`, debugImage(png, grid, size));
  }
}

async function traceMap(id: MapId, debugDir: string | undefined): Promise<TracedMap> {
  const overview = MAP_OVERVIEWS[id];
  const size = RADAR_IMAGE_SIZE / CELL;
  const { pngs, traced } = await traceOverviewLevels(id, size);

  const extraGrids = applyExtraFloors(id, traced, size);
  const floors = mapFloors(overview);
  const grids = [...traced, ...extraGrids].map((grid, floor) => {
    const level = floors[floor]?.level ?? 0;
    const seeds = floor < overview.levels.length ? seedsFor(id, level, grid, size) : [];
    return keepComponents(grid, size, seeds, MIN_SHARE);
  });

  if (debugDir !== undefined) await writeDebug(id, pngs, grids, size, debugDir);

  return {
    levels: grids.map((grid) => Buffer.from(packBits(grid)).toString('base64')),
    connectors: snapConnectors(id, grids, size),
  };
}

const debugDir = process.env[DEBUG_ENV];

for (const id of MAP_IDS) {
  const { levels, connectors } = await traceMap(id, debugDir);
  await Bun.write(`${OUTPUT_DIR}/${id}.ts`, render(levels, RADAR_IMAGE_SIZE / CELL, connectors));
  console.log(
    `${OUTPUT_DIR}/${id}.ts: ${levels.length} floor(s), ${connectors.length} connector(s).`,
  );
}
